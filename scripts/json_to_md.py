#!/usr/bin/env python3
"""Convert checklist-source/checklist.json -> src/checklist.md.

Usage: python3 scripts/json_to_md.py [input.json] [output.md]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "checklist-source" / "checklist.json"
out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src" / "checklist.md"

data = json.loads(src.read_text(encoding="utf-8"))
meta = data.get("metadata", {})
items = data["checklist"]


def clean(s):
    return " ".join(str(s).split())


lines = [f"# {clean(meta.get('standard', 'Accessibility Checklist'))}", ""]
if meta.get("section508Baseline"):
    lines += [f"> {clean(meta['section508Baseline'])}", ""]
lines += [
    "<!--",
    "  Generated by scripts/json_to_md.py. Format:",
    "    ## Phase name            (followed by optional 'Tools: a, b, c')",
    "    ### id | SC | Title | Level",
    "    - Section 508: ...  - ANDI module: ...  - Web: ...  - PDF: ...  - Hint: ... (repeatable)",
    "-->",
    "",
]

current_pass = None
seen_ids = set()
for it in items:
    if it["id"] in seen_ids:
        sys.exit(f"Duplicate id: {it['id']}")
    seen_ids.add(it["id"])
    if it["pass"] != current_pass:
        current_pass = it["pass"]
        lines += [f"## {clean(it['passName'])}", ""]
        tools = meta.get("tools", {}).get(f"pass{current_pass}")
        if tools:
            lines += [f"Tools: {', '.join(tools)}", ""]
    lines.append(f"### {it['id']} | {it['sc']} | {clean(it['title'])} | {it['level']}")
    if it.get("section508"):
        lines.append(f"- Section 508: {clean(it['section508'])}")
    if it.get("andiModule"):
        lines.append(f"- ANDI module: {clean(it['andiModule'])}")
    if it.get("webCheck"):
        lines.append(f"- Web: {clean(it['webCheck'])}")
    if it.get("pdfCheck"):
        lines.append(f"- PDF: {clean(it['pdfCheck'])}")
    for h in it.get("hints") or []:
        lines.append(f"- Hint: {clean(h)}")
    lines.append("")

out.write_text("\n".join(lines), encoding="utf-8")

# Coverage report against WCAG 2.2 A + AA
WCAG22_A_AA = """1.1.1 1.2.1 1.2.2 1.2.3 1.2.4 1.2.5 1.3.1 1.3.2 1.3.3 1.3.4 1.3.5 1.4.1 1.4.2 1.4.3 1.4.4
1.4.5 1.4.10 1.4.11 1.4.12 1.4.13 2.1.1 2.1.2 2.1.4 2.2.1 2.2.2 2.3.1 2.4.1 2.4.2 2.4.3 2.4.4 2.4.5
2.4.6 2.4.7 2.4.11 2.5.1 2.5.2 2.5.3 2.5.4 2.5.7 2.5.8 3.1.1 3.1.2 3.2.1 3.2.2 3.2.3 3.2.4 3.2.6
3.3.1 3.3.2 3.3.3 3.3.4 3.3.7 3.3.8 4.1.2 4.1.3""".split()
covered = {it["sc"] for it in items}
missing = [sc for sc in WCAG22_A_AA if sc not in covered]
print(f"Wrote {out.relative_to(ROOT)}: {len(items)} checks, {len(covered)} unique SC "
      f"(WCAG 2.2 A/AA has {len(WCAG22_A_AA)}).")
if missing:
    print("Missing SC:", ", ".join(missing))
